from app.agents.executor_agent import ExecutorAgent
from app.agents.planner_agent import PlannerAgent
from app.agents.repair_agent import RepairAgent
from app.agents.reviewer_agent import ReviewerAgent
from app.agents.solver_agent import SolverAgent
from app.models.planner_result import PlannerResult
from app.models.review_result import ReviewResult
from app.utils.json_parser import parse_json
from app.utils.tracer import add_trace
from app.agents.tester_agent import TesterAgent
from app.models.hidden_tests import HiddenTests

planner = PlannerAgent()
solver = SolverAgent()
tester = TesterAgent()
reviewer = ReviewerAgent()
repairer = RepairAgent()
executor = ExecutorAgent()

async def planner_node(state):

    planner_result = await planner.generate(
        user_prompt=state["problem"]
    )

    state["planner_model"] = planner_result.model

    add_trace(state, planner_result)

    print("=" * 80)
    print("PLANNER RAW RESPONSE")
    print(planner_result.response)
    print("=" * 80)

    state["plan"] = parse_json(
        planner_result.response,
        PlannerResult
    )

    return state

async def solver_node(state):

    prompt = f"""
Problem:

{state['problem']}

Algorithm:
{state['plan'].algorithm}

Strategy:
{state['plan'].strategy}

Time Complexity:
{state['plan'].time_complexity}

Space Complexity:
{state['plan'].space_complexity}

Edge Cases:
{chr(10).join("- " + x for x in state['plan'].edge_cases)}
"""
    solver_result = await solver.generate(
        user_prompt = prompt
    )
    state["solver_model"] = solver_result.model

    add_trace(state, solver_result)

    state["solution"] = solver_result.response
    state["solution_history"].append(solver_result.response)

    return state

async def tester_node(state):
    print("🔥 TESTER START")

    prompt = f"""
Problem

{state['problem']}

Generate strong hidden test cases.

Return only JSON matching the required schema.
"""

    tester_result = await tester.generate(
        user_prompt=prompt
    )
    print("=" * 80)
    print("TESTER RAW RESPONSE")
    print(tester_result.response)
    print("=" * 80)

    print("🔥 TESTER DONE")
    add_trace(state, tester_result)

    tests = parse_json(
        tester_result.response,
        HiddenTests,
    )

    state["hidden_tests"] = tests.hidden_tests

    return state

async def reviewer_node(state):

    prompt = f"""
Problem

{state['problem']}

Solution

{state['solution']}

Execution Report

Execution Report:

Compiled: {state["execution"].compiled}
Ran: {state["execution"].ran}
Passed Tests: {state["execution"].passed_tests}
Total Tests: {state["execution"].total_tests}
Exit Code: {state["execution"].exit_code}

Stdout:
{state["execution"].stdout}

Stderr:
{state["execution"].stderr}

Summary

Passed:
{state["execution"].passed_tests}

Out of:
{state["execution"].total_tests}

Detailed Outputs:
{chr(10).join(state["execution"].test_outputs)}
"""
    print("🔥 REVIEWER START")
    reviewer_result = await reviewer.generate(
        user_prompt=prompt
    )
    print("🔥 REVIEWER DONE")
    state["reviewer_model"] = reviewer_result.model

    add_trace(state, reviewer_result)
    
    
    review = parse_json(reviewer_result.response, ReviewResult)

    review.passed_tests = state["execution"].passed_tests
    review.total_tests = state["execution"].total_tests

    if review.total_tests > 0:
        correctness = int(
            100 * review.passed_tests / review.total_tests
        )
    else:
        correctness = 0

    review.correctness = correctness

    # Recompute overall score

    review.overall_score = int(
        
            review.correctness * 0.50 +
            review.efficiency * 0.20 +
            review.edge_cases * 0.15 +
            review.code_quality * 0.10 +
            review.explanation * 0.05
        
    )

    if review.overall_score >= state["acceptance_score"]:
        review.recommendation = "ACCEPT"
    else:
        review.recommendation = "REVISE"

    state["review"] = review
    state["review_history"].append(
        state["review"]
    )

    print("=" * 50)
    print("Router Debug")
    print("Score:", state["review"].overall_score)
    print("Acceptance:", state["acceptance_score"])
    print("Attempts:", state["repair_attempts"])
    print("Recommendation:", state["review"].recommendation)
    print("=" * 50)

    if state["review"].overall_score >= state["acceptance_score"]:
        state["final_status"] = "accepted"

    elif state["repair_attempts"] >= 2:
        state["final_status"] = "max_repairs_reached"

    else:
        state["final_status"] = "repairing"

    return state

async def repair_node(state):

    prompt = f"""
Problem:

{state['problem']}

Original Plan (generated by {state['planner_model']}):

{state['plan']}

Current Solution (generated by {state['solver_model']}):

{state['solution']}

Review Score:
{state['review'].overall_score}

Correctness:
{state['review'].correctness}

Efficiency:
{state['review'].efficiency}

Edge Cases:
{state['review'].edge_cases}

Code Quality:
{state['review'].code_quality}

Explanation:
{state['review'].explanation}

Issues:
{chr(10).join("- " + issue for issue in state["review"].issues)}

Your task is to improve the current solution.

Requirements:

- Fix every issue listed above.
- Preserve correctness.
- Keep O(n) time if possible.
- Keep O(1) extra space if possible.
- Improve readability.
- Add comments only if they improve understanding.
- Do NOT remove correct logic.
- Do NOT introduce unnecessary complexity.

Return ONLY valid C++ code.

Do not explain your changes.

Do not use markdown.

Do not wrap the code in ``` blocks.
"""

    repair_result = await repairer.generate(
        user_prompt=prompt
    )

    state["repair_model"] = repair_result.model

    add_trace(state, repair_result)

    state["solution"] = repair_result.response
    state["solution_history"].append(repair_result.response)

    state["repair_attempts"] += 1

    return state

async def executor_node(state):
    print("🔥 EXECUTOR START")

    test_cases = [
        {
            "input": tc.input,
            "expected_output": tc.expected_output,
        }
        for tc in state["hidden_tests"]
    ]

    result = await executor.execute(
        state["solution"],
        test_cases,
    )

    print("🔥 EXECUTOR DONE")
    state["execution"] = result
    state["execution_history"].append(result)

    return state
